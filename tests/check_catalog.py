#!/usr/bin/env python3
"""Consistency check for the vue-power-up rule catalog.

Verifies that every rule heading in skills/vue-power-up/references/*.md:
  - follows the template (id, title, severity, Why, Source for error/warn, Applies)
  - appears in rule-catalog.md's index with the same severity and reference file
  - is explained in docs/RATIONALE.md
and that the index has no rows without a matching rule.

Usage:
  python3 tests/check_catalog.py                # check, exit 1 on problems
  python3 tests/check_catalog.py --print-index  # print index rows generated from the headings
  python3 tests/check_catalog.py --write-index  # regenerate the index table in rule-catalog.md
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REFS = ROOT / "skills" / "vue-power-up" / "references"
CATALOG = REFS / "rule-catalog.md"
RATIONALE = ROOT / "docs" / "RATIONALE.md"

DOMAIN_ORDER = ["TS", "REACT", "COMP", "TPL", "CMPS", "PINIA", "NUXT", "SEC", "PERF", "TEST"]
INDEX_MARK = "<!-- index:start (generated by tests/check_catalog.py --write-index) -->"
INDEX_HEADER = "| Id | Severity | Rule | Applies | Ref |\n|---|---|---|---|---|\n"

HEADING = re.compile(r"^### (VUE-[A-Z]+-\d{3}) · (.+?)\s+`(error|warn|info)`\s*$")
ROW = re.compile(r"^\| (VUE-[A-Z]+-\d{3}) \| `?(error|warn|info)`? \| (.+?) \| (.+?) \| \[?`?([\w.-]+\.md)`?")


def parse_rules():
    rules = {}
    problems = []
    for path in sorted(REFS.glob("*.md")):
        if path.name in ("rule-catalog.md", "review.md"):
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        for i, line in enumerate(lines):
            if not line.startswith("### VUE-"):
                continue
            m = HEADING.match(line)
            if not m:
                problems.append(f"{path.name}:{i+1}: malformed rule heading: {line}")
                continue
            rid, title, sev = m.groups()
            # rule body = lines until next '### ' or '---'
            body = []
            for nxt in lines[i + 1:]:
                if nxt.startswith("### ") or nxt.strip() == "---":
                    break
                body.append(nxt)
            text = "\n".join(body)
            applies = re.search(r"^\*\*Applies:\*\* (.+?) ·", text, re.M)
            if rid in rules:
                problems.append(f"{path.name}:{i+1}: duplicate id {rid}")
            if "**Why:**" not in text:
                problems.append(f"{rid}: missing **Why:**")
            if sev in ("error", "warn") and not re.search(r"^\*\*Source:\*\* https://", text, re.M):
                problems.append(f"{rid}: {sev} rule needs an official **Source:** URL")
            if not applies:
                problems.append(f"{rid}: missing **Applies:** ... · **Exceptions:** line")
            if "**Exceptions:**" not in text:
                problems.append(f"{rid}: missing **Exceptions:**")
            rules[rid] = {
                "title": title,
                "sev": sev,
                "file": path.name,
                "applies": applies.group(1) if applies else "?",
            }
    return rules, problems


def main():
    rules, problems = parse_rules()

    if "--print-index" in sys.argv or "--write-index" in sys.argv:
        order = [d for d in DOMAIN_ORDER]
        def key(rid):
            dom = rid.split("-")[1]
            return (order.index(dom) if dom in order else 99, rid)
        rows = [
            f"| {rid} | `{r['sev']}` | {r['title'].replace('|', '/')} | {r['applies'].replace('|', '/')} | [`{r['file']}`]({r['file']}) |"
            for rid, r in sorted(rules.items(), key=lambda kv: key(kv[0]))
        ]
        if "--print-index" in sys.argv:
            print("\n".join(rows))
            return 0
        text = CATALOG.read_text(encoding="utf-8")
        head, sep, _ = text.partition(INDEX_MARK)
        if not sep:
            print(f"rule-catalog.md has no '{INDEX_MARK}' marker")
            return 1
        CATALOG.write_text(head + sep + "\n" + INDEX_HEADER + "\n".join(rows) + "\n", encoding="utf-8")
        print(f"wrote {len(rows)} index rows")
        return 0

    catalog_rows = {}
    for line in CATALOG.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if m:
            rid, sev, _title, _applies, fname = m.groups()
            catalog_rows[rid] = (sev, fname)

    for rid, r in rules.items():
        row = catalog_rows.get(rid)
        if not row:
            problems.append(f"{rid}: missing from rule-catalog.md index")
            continue
        if row[0] != r["sev"]:
            problems.append(f"{rid}: severity mismatch (rule {r['sev']}, index {row[0]})")
        if row[1] != r["file"]:
            problems.append(f"{rid}: reference mismatch (rule in {r['file']}, index says {row[1]})")
    for rid in catalog_rows:
        if rid not in rules:
            problems.append(f"{rid}: index row has no matching rule heading")

    rationale = RATIONALE.read_text(encoding="utf-8")
    for rid in rules:
        if not re.search(rf"^#### {re.escape(rid)}\b", rationale, re.M):
            problems.append(f"{rid}: no '#### {rid}' entry in docs/RATIONALE.md")

    if problems:
        print("\n".join(problems))
        print(f"\nFAIL: {len(problems)} problem(s) across {len(rules)} rules")
        return 1
    print(f"OK: {len(rules)} rules consistent across references, catalog index and RATIONALE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
